return {
  "andythigpen/nvim-coverage",
  dependencies = { "nvim-lua/plenary.nvim" },
  cmd = {
    "Coverage",
    "CoverageLoad",
    "CoverageLoadLcov",
    "CoverageToggle",
    "CoverageShow",
    "CoverageHide",
    "CoverageSummary",
    "CoverageClear",
  },
  keys = {
    {
      "<leader>tcl",
      function()
        require("coverage").load(true)
      end,
      desc = "Load test coverage",
    },
    {
      "<leader>tct",
      function()
        require("coverage").toggle()
      end,
      desc = "Toggle test coverage",
    },
    {
      "<leader>tcs",
      function()
        require("coverage").summary()
      end,
      desc = "Test coverage summary",
    },
  },
  opts = { auto_reload = true, lang = { python = { coverage_file = "coverage.json" } } },
  config = function(_, opts)
    require("coverage").setup(opts)
    -- Read the report generated by the project, without invoking a different
    -- global Python/coverage installation than the one that ran the tests.
    require("coverage.languages.python").load = function(callback)
      local path = require("coverage.util").get_coverage_file(opts.lang.python.coverage_file)
      local ok, data = pcall(function()
        return vim.json.decode(table.concat(vim.fn.readfile(path), "\n"))
      end)
      if
        not ok
        or type(data) ~= "table"
        or type(data.files) ~= "table"
        or type(data.totals) ~= "table"
      then
        vim.notify(
          "Generate coverage.json with pytest-cov first (see IDE-WORKFLOW.md)",
          vim.log.levels.WARN
        )
        return
      end
      callback(data)
    end
  end,
}
